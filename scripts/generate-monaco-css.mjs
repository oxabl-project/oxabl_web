// Writes src/styles/monaco.css: every stylesheet that the Monaco modules
// imported by src/lib/monacoAbl.ts pull in, in module evaluation order.
//
// Astro drops the CSS of a dynamically imported client chunk, and the
// playground may not put Monaco's styles on the page before the visitor asks
// for it, so TryOxabl injects this file at click time (imported with ?inline).
// Run this after changing the Monaco imports or the monaco-editor version;
// `--check` fails when the committed file is stale.
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative, resolve } from "node:path"

const root = resolve(import.meta.dirname, "..")
const monacoRoot = join(root, "node_modules/monaco-editor/esm/vs")
const entryFile = join(root, "src/lib/monacoAbl.ts")
const outFile = join(root, "src/styles/monaco.css")

const entries = [
  ...readFileSync(entryFile, "utf8").matchAll(
    /(?:import\s+(?:[^"']*from\s+)?)["']monaco-editor\/([^"'?]+)["']/g
  ),
].map((m) => join(monacoRoot, `${m[1]}.js`))

const seen = new Set()
const sheets = []
const specifier = /(?:^|\n)\s*(?:import|export)\s+(?:[^"';]*?\sfrom\s+)?["']([^"']+)["']/g

function visit(file) {
  if (seen.has(file)) return
  seen.add(file)
  if (!existsSync(file)) throw new Error(`missing Monaco module ${file}`)
  const source = readFileSync(file, "utf8")
  for (const m of source.matchAll(specifier)) {
    const spec = m[1]
    if (!spec.startsWith(".")) continue
    const target = resolve(dirname(file), spec)
    if (target.endsWith(".css")) {
      if (!sheets.includes(target)) sheets.push(target)
    } else {
      visit(target)
    }
  }
}
for (const entry of entries) visit(entry)

const header =
  "/* Generated by scripts/generate-monaco-css.mjs. Do not edit. */\n"
const body = sheets
  .map((sheet) => `@import "${relative(dirname(outFile), sheet)}";`)
  .join("\n")
const next = `${header}${body}\n`

if (process.argv.includes("--check")) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : ""
  if (current !== next) {
    console.error("src/styles/monaco.css is stale: run pnpm monaco-css:generate")
    process.exit(1)
  }
  console.log(`Monaco stylesheet list is current (${sheets.length} files)`)
} else {
  writeFileSync(outFile, next)
  console.log(`Wrote ${relative(root, outFile)} (${sheets.length} files)`)
}
